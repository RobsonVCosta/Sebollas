#!/usr/bin/env python3
"""Convert the supplied Going Home piano score reduction to three PSG voices."""
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'resources/generated'
SCORE = ROOT / 'resources/going-home-score.json'
SEMITONES = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}


def midi(pitch):
    if pitch == 'R':
        return 0
    match = re.fullmatch(r'([A-G])([#b]?)([0-8])', pitch)
    if not match:
        raise ValueError(f'Invalid pitch: {pitch}')
    name, accidental, octave = match.groups()
    return (int(octave) + 1) * 12 + SEMITONES[name] + {'': 0, '#': 1, 'b': -1}[accidental]


def period(note):
    value = round(1789772.5 / (16 * 440 * 2 ** ((note - 69) / 12))) if note else 0
    assert 0 <= value <= 4095, (note, value)
    return value


def compile_score(score):
    rate = Fraction(60 * score['tick_rate'], score['tempo_bpm'])
    beats = sum(Fraction(measure['beats']) for measure in score['measures'])
    tracks = {channel: [0] * round(beats * rate) for channel in 'ABC'}
    for channel, track in tracks.items():
        cursor = Fraction(0)
        pending = None
        for number, measure in enumerate(score['measures'], 1):
            start = cursor
            for token in measure[channel].split():
                pitch, duration = token.split(':')
                tied = duration.endswith('~')
                duration = Fraction(duration.rstrip('~'))
                note = midi(pitch)
                assert duration > 0
                # Merge ties before quantization so there is no artificial gap.
                if pending is not None:
                    assert pending[2] == note, (number, channel, 'broken tie')
                    begin = pending[0]
                else:
                    begin = cursor
                cursor += duration
                pending = (begin, cursor, note) if tied else None
                if tied:
                    continue
                a, b = round(begin * rate), round(cursor * rate)
                assert 0 <= a < b <= len(track)
                release = 1 if note and b - a >= 3 else 0
                track[a:b - release] = [period(note)] * (b - a - release)
            assert cursor - start == Fraction(measure['beats']), (number, channel)
        assert pending is None, (channel, 'unfinished tie')

    events = []
    for tones in zip(*(tracks[channel] for channel in 'ABC')):
        if events and events[-1][:3] == tones and events[-1][3] < 255:
            events[-1] = (*tones, events[-1][3] + 1)
        else:
            events.append((*tones, 1))
    return events


def main():
    score = json.loads(SCORE.read_text())
    assert hashlib.sha256((ROOT / 'resources' / score['source']).read_bytes()).hexdigest() == score['source_sha256']
    events = compile_score(score)
    packed = bytearray()
    lines = ['; Generated by tools/build_ending_music.py; A=bass, B=inner voice, C=melody.', 'GoingHomeNotes:']
    for a, b, c, ticks in events:
        lines.extend((f'    dw {a},{b},{c}', f'    db {ticks}'))
        packed.extend(a.to_bytes(2, 'little') + b.to_bytes(2, 'little') + c.to_bytes(2, 'little') + bytes([ticks]))
    lines.append('GoingHomeNotesEnd:')
    assert len(packed) <= 8192, 'Ending arrangement must fit ASCII8 bank 6'
    OUT.mkdir(exist_ok=True)
    (OUT / 'going_home.inc').write_text('\n'.join(lines) + '\n')
    (OUT / 'going_home.bin').write_bytes(packed)
    manifest = {key: score[key] for key in ('title', 'source', 'source_sha256', 'tempo_bpm', 'tick_rate')}
    manifest.update(measures=len(score['measures']), beats=sum(m['beats'] for m in score['measures']),
                    events=len(events), ticks=sum(e[3] for e in events), event_bytes=7,
                    channels={'A': 'bass', 'B': 'inner voice', 'C': 'melody'}, rom_bank=6)
    manifest['seconds'] = manifest['ticks'] / manifest['tick_rate']
    manifest['loop'] = False
    (OUT / 'going_home_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f"Going Home: {manifest['measures']} measures, three voices, {manifest['seconds']:.2f}s, {len(packed)} bytes")


if __name__ == '__main__':
    main()
